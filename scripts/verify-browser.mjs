import {chromium} from 'playwright'
import {mkdir} from 'node:fs/promises'
import assert from 'node:assert/strict'
const target=process.env.TARGET_URL||'http://127.0.0.1:4173'
const artifacts=new URL('../artifacts/',import.meta.url).pathname;await mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
const settle=async()=>page.evaluate(()=>new Promise(resolve=>{let previous=scrollY,stable=0;const tick=()=>{stable=Math.abs(scrollY-previous)<.1?stable+1:0;previous=scrollY;if(stable>=18)resolve(true);else requestAnimationFrame(tick)};requestAnimationFrame(tick)}))
const pose=()=>page.locator('.cinema-stage').getAttribute('data-journey-position')
await page.goto(target)
await page.locator('.loader').waitFor({state:'detached',timeout:15000})
await page.waitForFunction(()=>Number(document.querySelector('.gallery-canvas').dataset.imageCount)>=112)
assert.equal(await page.locator('video[autoplay]').count(),0)
assert.equal(await page.getByRole('button',{name:/Pause journey|Play journey|Replay journey/}).count(),0)
const idle=await pose();await page.waitForTimeout(1000);assert.equal(await pose(),idle,'Scene must not autoplay')
await page.mouse.wheel(0,600);await page.waitForFunction(()=>Number(document.querySelector('.cinema-stage').dataset.scrollProgress)>.01);await settle()
const wheelPose=Number(await pose());assert.ok(wheelPose>0)
await page.mouse.wheel(0,-400);await settle();assert.ok(Number(await pose())<wheelPose,'Reverse wheel input must reverse the journey')
const range=await page.locator('.cinema').evaluate(el=>({top:el.offsetTop,range:el.offsetHeight-innerHeight}))
const stages=[[.2,'tunnel'],[.42,'gather'],[.6,'trail'],[.83,'write'],[.95,'hold'],[1,'ink']]
for(const [progress,phase] of stages){
 await page.evaluate(y=>scrollTo(0,y),range.top+range.range*progress)
 await page.waitForFunction(p=>Math.abs(Number(document.querySelector('.cinema-stage').dataset.scrollProgress)-p)<.002,progress)
 await settle()
 assert.equal(await page.locator('.cinema-stage').getAttribute('data-phase'),phase)
 await page.waitForTimeout(600)
 await page.screenshot({path:artifacts+`scroll-${phase}.png`})
 console.log('Scroll stage:',progress,phase)
}
await page.evaluate(()=>{window.__frame=document.querySelector('.gallery-canvas').toDataURL()})
const stopped=await pose();await page.waitForTimeout(800);assert.equal(await pose(),stopped)
assert.ok(await page.evaluate(()=>window.__frame===document.querySelector('.gallery-canvas').toDataURL()),'Image geometry must remain unchanged without scrolling')
await page.evaluate(y=>scrollTo(0,y),range.top+range.range*.6);await settle();assert.equal(await page.locator('.cinema-stage').getAttribute('data-phase'),'trail')
console.log('No autoplay; wheel control; reverse scrubbing; unchanged idle frame passed')
await page.goto(target+'/about');await page.getByRole('heading',{name:'From mind to market.',level:1}).waitFor()
assert.equal(await page.locator('.webgl-media-canvas').count(),0)
assert.equal(await page.locator('img[data-webgl-media]').count(),0)
const photo=page.locator('.page-panorama');const before=await photo.boundingBox();await photo.hover();await page.waitForTimeout(700);const after=await photo.boundingBox()
assert.ok(Math.abs(before.width-after.width)<.1&&Math.abs(before.height-after.height)<.1,'Photos must not bulge or scale on hover')
assert.equal(await photo.evaluate(el=>getComputedStyle(el).transform),'none')
await page.screenshot({path:artifacts+'flat-about.png'})
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Services',exact:true}).click()
await page.locator('.page-curl-overlay.is-turning').waitFor({timeout:10000})
const began=Date.now();await page.waitForTimeout(1100)
assert.equal(await page.locator('.page-curl-overlay.is-turning').count(),1,'Page turn must remain visible after one second')
const coverage=await page.locator('.page-curl-overlay').evaluate(c=>{const gl=c.getContext('webgl2');const pixels=new Uint8Array(c.width*c.height*4);gl.readPixels(0,0,c.width,c.height,gl.RGBA,gl.UNSIGNED_BYTE,pixels);let opaque=0;for(let i=3;i<pixels.length;i+=4)if(pixels[i]>80)opaque++;return opaque/(c.width*c.height)})
assert.ok(coverage>.05,'Folded outgoing page must still be visible')
await page.screenshot({path:artifacts+'slow-page-curl.png'})
await page.locator('.page-curl-overlay.is-turning').waitFor({state:'hidden',timeout:10000})
assert.ok(Date.now()-began>=2800,'Page curl must take approximately 3.2 seconds')
console.log('Flat native photos and slow visible page curl passed')
for(const width of [768,390]){
 await page.setViewportSize({width,height:844});await page.goto(target);await page.waitForFunction(()=>Boolean(document.querySelector('.cinema-stage')))
 await page.locator('.loader').waitFor({state:'detached',timeout:15000})
 await page.evaluate(()=>scrollTo(0,0));await settle()
 await page.screenshot({path:artifacts+`scroll-${width}-hero.png`})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const r=await page.locator('.cinema').evaluate(el=>el.offsetHeight-innerHeight)
 await page.evaluate(y=>scrollTo(0,y),r*.27);await settle();await page.waitForTimeout(650)
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.screenshot({path:artifacts+`scroll-${width}-phrase.png`})
}
const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
await reduced.goto(target);assert.equal(await reduced.locator('.loader').count(),0)
assert.ok(await reduced.locator('.cinema').evaluate(el=>el.offsetHeight)<1000)
await reduced.goto(target+'/contact');await reduced.getByRole('button',{name:'Prepare a project enquiry'}).click()
await reduced.getByLabel('Your name',{exact:true}).fill('Test Visitor');await reduced.getByLabel('Email address',{exact:true}).fill('visitor@example.com');await reduced.getByLabel('A little about your idea',{exact:true}).fill('A professional website for our software studio.')
await reduced.getByRole('button',{name:'Prepare enquiry'}).click();await reduced.getByRole('heading',{name:'Your project brief.'}).waitFor()
await reduced.keyboard.press('Escape')
assert.deepEqual(errors,[])
console.log('Tablet/mobile overflow, reduced motion, enquiry and browser errors passed')
await browser.close()
