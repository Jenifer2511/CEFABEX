import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
try{
 const page=await browser.newPage()
 const errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 for(const width of [1440,768,390]){
  await page.setViewportSize({width,height:900})
  await page.goto(process.env.TARGET_URL||'http://127.0.0.1:4173')
  await page.getByRole('heading',{name:'Ideas into impact.',exact:true}).waitFor()
  assert.equal(await page.locator('canvas,.loader,.cinema,.page-curl-overlay').count(),0)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal overflow')
  const cta=page.getByRole('button',{name:'Start a project',exact:true})
  assert.ok((await cta.boundingBox()).y<900,'Primary action visible')
  await cta.click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button',{name:'Prepare enquiry'}).click()
  await page.getByText('Please enter your name.',{exact:true}).waitFor()
  await page.getByLabel('Your name',{exact:true}).fill('Test Client')
  await page.getByLabel('Email address',{exact:true}).fill('client@example.com')
  await page.getByLabel('A little about your idea').fill('A company website with an accessible project portfolio.')
  await page.getByRole('button',{name:'Prepare enquiry'}).click()
  await page.getByRole('heading',{name:'Your project brief.'}).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(),0)
  await page.locator('summary').filter({hasText:'Can you help shape an early idea?'}).click()
  assert.ok(await page.locator('details[open]').count())
  if(width<=600)await page.getByRole('button',{name:'Open navigation'}).click()
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Services',exact:true}).click()
  await page.locator('.page-service-list').waitFor()
  assert.equal(new URL(page.url()).pathname,'/services')
  await page.goBack()
  await page.locator('.simple-hero').waitFor()
  await page.screenshot({path:`work/home-${width}.png`,fullPage:true})
 }
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.reload()
 await page.locator('.simple-hero').waitFor()
 assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto')
 assert.equal(await page.evaluate(()=>document.getAnimations().length),0)
 assert.deepEqual(errors,[])
 console.log('Desktop, tablet, mobile, navigation, FAQ, enquiry validation and reduced motion passed.')
}finally{await browser.close()}
