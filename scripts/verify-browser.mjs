import { chromium } from 'playwright'
import {mkdir} from 'node:fs/promises'
import assert from 'node:assert/strict'
const target=process.env.TARGET_URL||'http://127.0.0.1:4173'
const artifacts=new URL('../artifacts/',import.meta.url).pathname;await mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
await page.goto(target)
await page.locator('.loader').waitFor({state:'detached',timeout:15000})
await page.waitForFunction(()=>Number(document.querySelector('.cinema-stage').dataset.elapsed)>=1)
assert.ok(Number(await page.locator('.gallery-canvas').getAttribute('data-image-count'))>=112)
await page.getByRole('button',{name:'Pause journey'}).click()
const paused=await page.locator('.cinema-stage').getAttribute('data-elapsed');await page.waitForTimeout(650)
assert.equal(await page.locator('.cinema-stage').getAttribute('data-elapsed'),paused)
await page.screenshot({path:artifacts+'timed-tunnel.png'})
await page.getByRole('button',{name:'Play journey'}).click()
for(const [at,phase,label] of [[14.5,'tunnel','tunnel-15s'],[16,'gather','gather'],[21,'trail','trail-start'],[29,'trail','trail-inward'],[34,'write','snake-letter-route'],[38.5,'hold','image-word'],[40.5,'ink','final-text']]){
 await page.waitForFunction(t=>Number(document.querySelector('.cinema-stage').dataset.elapsed)>=t,at,{timeout:45000})
 const actual=await page.locator('.cinema-stage').getAttribute('data-phase')
 if(at!==14.5)assert.equal(actual,phase)
 console.log('Stage',at,actual)
 await page.screenshot({path:artifacts+label+'.png'})
}
await page.getByRole('button',{name:'Replay journey'}).waitFor()
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'About',exact:true}).click()
await page.locator('.page-curl-overlay.is-turning').waitFor({timeout:10000})
await page.screenshot({path:artifacts+'page-curl-start.png'})
await page.waitForTimeout(120)
await page.screenshot({path:artifacts+'page-curl-mid.png'})
await page.waitForURL('**/about')
await page.locator('.page-curl-overlay.is-turning').waitFor({state:'hidden',timeout:10000})
await page.getByRole('heading',{level:1,name:'From mind to market.'}).waitFor()
await page.screenshot({path:artifacts+'about-webgl.png'})
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Projects',exact:true}).click()
await page.waitForURL('**/projects')
await page.locator('.page-curl-overlay.is-turning').waitFor({state:'hidden',timeout:10000})
console.log('Actual-page curl navigation passed')
const mobile=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
await mobile.goto(target+'/contact')
await mobile.getByRole('heading',{level:1}).waitFor()
await mobile.getByRole('button',{name:'Prepare a project enquiry'}).click()
await mobile.getByLabel('Your name',{exact:true}).fill('Test Visitor')
await mobile.getByLabel('Email address',{exact:true}).fill('visitor@example.com')
await mobile.getByLabel('A little about your idea',{exact:true}).fill('A connected software experience for our business.')
await mobile.getByRole('button',{name:'Prepare enquiry'}).click()
await mobile.getByRole('heading',{name:'Your project brief.'}).waitFor()
const download=mobile.waitForEvent('download');await mobile.getByRole('button',{name:'Download brief'}).click();assert.equal((await download).suggestedFilename(),'cefabex-project-brief.txt')
await mobile.keyboard.press('Escape')
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
await mobile.goto(target)
await mobile.getByRole('link',{name:'Skip the journey'}).waitFor()
assert.equal(await mobile.locator('.loader').count(),0)
assert.ok(await mobile.locator('.cinema').evaluate(el=>el.offsetHeight)<1000)
await mobile.screenshot({path:artifacts+'reduced-home.png'})
console.log('Pause, timed stages, page curl, form and reduced motion passed. Browser errors:',errors)
await browser.close();assert.deepEqual(errors,[])
