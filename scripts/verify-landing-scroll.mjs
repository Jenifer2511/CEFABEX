import {chromium} from 'playwright'
import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'

const target=process.env.TARGET_URL||'http://127.0.0.1:4173'
const artifacts=new URL('../artifacts/',import.meta.url).pathname
await mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const errors=[]
const page=await browser.newPage({viewport:{width:1440,height:1000}})
page.on('pageerror',e=>errors.push(e.message))
await page.addInitScript(()=>sessionStorage.setItem('cefabex-ready','1'))
const settle=async()=>page.evaluate(()=>new Promise(resolve=>{let previous=scrollY,stable=0;const tick=()=>{stable=Math.abs(scrollY-previous)<.1?stable+1:0;previous=scrollY;if(stable>=20)resolve(true);else requestAnimationFrame(tick)};requestAnimationFrame(tick)}))
const go=async(position)=>{await page.evaluate(y=>scrollTo(0,y),position);await settle()}
const scene=async(selector,progress)=>{
 const range=await page.locator(selector).evaluate(el=>({start:Number(el.dataset.scrollStart),end:Number(el.dataset.scrollEnd)}))
 assert.ok(Number.isFinite(range.start)&&range.end>range.start,`${selector} needs a valid scroll range`)
 await go(range.start+(range.end-range.start)*progress)
}
await page.goto(target)
await page.waitForFunction(()=>document.querySelector('main[data-homepage]')?.dataset.homeMotion==='ready')
await page.waitForFunction(()=>Number(document.querySelector('.work-journey').dataset.scrollEnd)>0)
await settle()

const picture=page.locator('.company-picture').first()
const pictureTop=await picture.evaluate(el=>el.getBoundingClientRect().top+scrollY)
await go(pictureTop-900)
const masked=await picture.evaluate(el=>getComputedStyle(el).clipPath)
await go(pictureTop-100)
assert.notEqual(await picture.evaluate(el=>getComputedStyle(el).clipPath),masked)
assert.equal(await picture.locator('img').evaluate(el=>getComputedStyle(el).transform),'none')
await page.screenshot({path:artifacts+'landing-company.png'})

for(const [progress,index] of [[.08,0],[.48,1],[.88,2]]){
 await scene('.expertise-journey',progress)
 assert.equal(await page.locator('.expertise-journey').getAttribute('data-active-stage'),String(index))
 assert.equal(await page.getByRole('tab',{selected:true}).getAttribute('id'),`expertise-tab-${index}`)
 await page.screenshot({path:artifacts+`landing-expertise-${index}.png`})
}
const idle=await page.locator('.expertise-journey').getAttribute('data-scroll-progress')
const flatFrame=await page.locator('.expertise-image').last().evaluate(el=>getComputedStyle(el).clipPath)
await page.waitForTimeout(600)
assert.equal(await page.locator('.expertise-journey').getAttribute('data-scroll-progress'),idle)
assert.equal(await page.locator('.expertise-image').last().evaluate(el=>getComputedStyle(el).clipPath),flatFrame)
await scene('.expertise-journey',.08)
await page.locator('#expertise-tab-0').focus()
await page.keyboard.press('ArrowRight')
await page.waitForFunction(()=>document.querySelector('.expertise-journey').dataset.activeStage==='1')

await scene('.work-journey',0)
const startX=(await page.locator('.work-slide').first().boundingBox()).x
await scene('.work-journey',.5)
await page.screenshot({path:artifacts+'landing-projects-middle.png'})
await scene('.work-journey',1)
const endX=(await page.locator('.work-slide').first().boundingBox()).x
const last=await page.locator('.work-slide').last().boundingBox()
assert.ok(startX-endX>2000,'Vertical scroll must travel through the horizontal project collection')
assert.ok(last.x>=0&&last.x+last.width<=1441,'Last project must fit at the end of the rail')
await scene('.work-journey',.25)
assert.ok((await page.locator('.work-slide').first().boundingBox()).x>endX,'Reverse scroll must reverse the project rail')
await page.locator('.work-slide').first().focus()
await page.keyboard.press('Tab')
await settle()
assert.equal(await page.locator('.work-slide').nth(1).evaluate(el=>el===document.activeElement),true)
const focused=await page.locator('.work-slide').nth(1).boundingBox()
assert.ok(focused.x>=0&&focused.x+focused.width<=1441,'Keyboard focus must bring an offscreen project into view')

const manifesto=page.locator('.manifesto-journey')
const manifestoTop=await manifesto.evaluate(el=>el.offsetTop)
await go(manifestoTop-500)
const beforeInk=Number(await page.locator('.manifesto-word').last().evaluate(el=>getComputedStyle(el).opacity))
await go(manifestoTop+600)
assert.ok(Number(await page.locator('.manifesto-word').last().evaluate(el=>getComputedStyle(el).opacity))>beforeInk)
await page.screenshot({path:artifacts+'landing-manifesto.png'})

for(const [progress,index] of [[.08,0],[.48,1],[.88,2]]){
 await scene('.process-journey',progress)
 assert.equal(await page.locator('.process-journey').getAttribute('data-active-step'),String(index))
 assert.ok(Number(await page.locator('.process-step-copy').nth(index).evaluate(el=>getComputedStyle(el).opacity))>.98)
 await page.screenshot({path:artifacts+`landing-process-${index}.png`})
}
const footerTop=await page.locator('.studio-footer').evaluate(el=>el.getBoundingClientRect().top+scrollY)
await go(footerTop-180)
await page.screenshot({path:artifacts+'landing-footer.png'})
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
console.log('Desktop: image masks, three service chapters, horizontal projects, manifesto, process and footer passed')

for(const [width,height] of [[768,900],[390,844]]){
 await page.setViewportSize({width,height});await page.goto(target)
 await page.waitForFunction(()=>document.querySelector('.expertise-journey')?.classList.contains('has-scroll-chapters'))
 await scene('.expertise-journey',.88)
 assert.equal(await page.locator('.expertise-journey').getAttribute('data-active-stage'),'2')
 const stage=await page.locator('.expertise-stage').boundingBox()
 const tabs=await page.locator('.expertise-tabs').boundingBox()
 assert.ok(tabs.y+tabs.height<=stage.y+stage.height+1,'Service controls must fit inside the sticky stage')
 const action=await page.locator('.expertise-copy > button').boundingBox()
 assert.ok(action.y+action.height<=tabs.y-8,'Service text and action must not overlap the chapter controls')
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.screenshot({path:artifacts+`landing-${width}-expertise.png`})
 assert.equal(await page.locator('.work-journey.has-work-scroll').count(),0)
 const work=await page.locator('.work-slide').first().evaluate(el=>el.getBoundingClientRect().top+scrollY)
 await go(work-100);await page.screenshot({path:artifacts+`landing-${width}-project.png`})
 assert.equal(await page.locator('.work-slide').count(),5)
}
await page.setViewportSize({width:390,height:650})
await page.waitForFunction(()=>!document.querySelector('.expertise-journey').classList.contains('has-scroll-chapters'))
await page.locator('#expertise').scrollIntoViewIfNeeded();await settle()
await page.getByRole('tab',{name:'Apps',exact:true}).click()
assert.equal(await page.locator('.expertise-journey').getAttribute('data-active-stage'),'1')
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
await page.screenshot({path:artifacts+'landing-short-viewport.png'})
const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
reduced.on('pageerror',e=>errors.push(e.message))
await reduced.goto(target)
assert.equal(await reduced.locator('.pin-spacer,.has-scroll-chapters').count(),0)
assert.equal(await reduced.locator('.manifesto-word').last().evaluate(el=>getComputedStyle(el).opacity),'1')
await reduced.getByRole('tab',{name:/Software/}).click()
assert.equal(await reduced.locator('.expertise-journey').getAttribute('data-active-stage'),'2')
assert.equal(await reduced.locator('.work-slide').count(),5)
assert.equal(await reduced.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
console.log('Tablet/phone: readable chapters, stacked projects and no overflow; reduced motion and keyboard controls passed')
await page.setViewportSize({width:1440,height:1000});await page.goto(target)
await page.waitForFunction(()=>document.querySelectorAll('.pin-spacer').length===2)
await page.locator('.desktop-nav a[href="/about"]').click()
await page.getByRole('heading',{name:'From mind to market.',level:1}).waitFor()
await page.locator('.page-curl-overlay.is-turning').waitFor({state:'hidden',timeout:15000})
assert.equal(await page.locator('.pin-spacer').count(),0)
await page.getByRole('link',{name:'CEFABEX home',exact:true}).click()
await page.waitForFunction(()=>document.querySelectorAll('.pin-spacer').length===2)
console.log('SPA navigation removes and restores the landing scroll scenes without duplicate pins')
assert.deepEqual(errors,[])
await browser.close()
