import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const target=process.env.TARGET_URL||'http://127.0.0.1:4173'
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
try{
 const page=await browser.newPage({viewport:{width:1280,height:900}})
 await page.goto(target)
 await page.locator('.brand-canvas[data-context="ready"]').waitFor({timeout:20000})
 assert.equal(await page.locator('.brand-canvas').getAttribute('data-effect'),'originkit-endless-square-tunnel')
 // The sequence advances only from wheel/scroll input, holds and reverses.
 assert.equal(await page.getByRole('button',{name:'Play the reveal'}).count(),0)
 const before=Number(await page.locator('.brand-journey').getAttribute('data-progress'))
 await page.mouse.wheel(0,700)
 await page.waitForFunction(start=>Number(document.querySelector('.brand-journey').dataset.progress)>start+.05,before)
 await page.waitForTimeout(1500)
 const held=await page.locator('.brand-canvas').screenshot()
 await page.mouse.move(640,450)
 await page.waitForTimeout(500)
 assert.deepEqual(await page.locator('.brand-canvas').screenshot(),held,'Idle and pointer movement do not advance the sequence')
 const forward=Number(await page.locator('.brand-journey').getAttribute('data-progress'))
 await page.mouse.wheel(0,-350)
 await page.waitForTimeout(1500)
 assert.ok(Number(await page.locator('.brand-journey').getAttribute('data-progress'))<forward,'Reverse wheel input reverses the sequence')
 // A lost GPU context must not remove the text or controls.
 await page.locator('.brand-canvas').evaluate(canvas=>{window.__tunnelRecovery=canvas.getContext('webgl2').getExtension('WEBGL_lose_context');window.__tunnelRecovery.loseContext()})
 await page.locator('.brand-canvas[data-context="lost"]').waitFor({state:'attached'})
 await page.evaluate(()=>scrollTo(0,(document.querySelector('.brand-journey').offsetHeight-innerHeight)*.9))
 await page.waitForTimeout(1000)
 assert.equal(await page.locator('.brand-resolution').evaluate(el=>getComputedStyle(el).visibility),'visible')
 assert.equal(await page.locator('.brand-name').evaluate(el=>getComputedStyle(el).opacity),'1','Fallback title stays readable')
 assert.equal(await page.locator('.name-echo-far').evaluate(el=>getComputedStyle(el).display),'none','Fallback omits decorative title copies')
 await page.locator('.journey-bottom > a').click()
 await page.waitForTimeout(1500)
 assert.ok((await page.locator('#company').boundingBox()).y<900)
 await page.evaluate(()=>window.__tunnelRecovery.restoreContext())
 await page.locator('.brand-canvas[data-context="ready"]').waitFor({timeout:15000})
 await page.evaluate(()=>scrollTo(0,(document.querySelector('.brand-journey').offsetHeight-innerHeight)*.35))
 await page.waitForTimeout(1200)
 assert.ok(Math.abs(Number(await page.locator('.brand-canvas').getAttribute('data-frame-progress'))-.35)<.01,'Restored tunnel redraws its scroll pose')
 assert.equal(await page.locator('.brand-canvas').evaluate(canvas=>canvas.getContext('webgl2').getError()),0,'Restored GPU resources are valid')
 assert.equal(await page.locator('.brand-journey').getAttribute('data-scene'),'ready')
 await page.close()
 // Also exercise a device where WebGL is unavailable from the beginning.
 const fallback=await browser.newPage({viewport:{width:390,height:844}})
 await fallback.addInitScript(()=>{
  const original=HTMLCanvasElement.prototype.getContext
  HTMLCanvasElement.prototype.getContext=function(type,...args){if(type==='webgl'||type==='webgl2')return null;return original.call(this,type,...args)}
 })
 await fallback.goto(target)
 await fallback.locator('.brand-canvas[data-render-mode="fallback"]').waitFor({timeout:20000})
 await fallback.evaluate(()=>scrollTo(0,(document.querySelector('.brand-journey').offsetHeight-innerHeight)*.9))
 await fallback.waitForTimeout(1000)
 assert.equal(await fallback.locator('.brand-resolution').evaluate(el=>getComputedStyle(el).visibility),'visible')
 await fallback.emulateMedia({reducedMotion:'reduce'})
 await fallback.locator('.brand-canvas').waitFor({state:'detached'})
 assert.equal(await fallback.locator('.pin-spacer').count(),0)
 assert.equal(await fallback.locator('.brand-journey').evaluate(el=>el.classList.contains('is-static')),true)
 assert.equal(await fallback.locator('.reveal-mask').count(),0)
 const staticPage=await browser.newPage({javaScriptEnabled:false})
 await staticPage.goto(target)
 await staticPage.getByRole('heading',{name:'CEFABEX. Build what comes next.'}).waitFor()
 await staticPage.getByRole('link',{name:'Email cefabex.cfb@gmail.com'}).waitFor()
 console.log('PASS: wheel-driven progression/hold/reversal, WebGL context loss/recovery, initial WebGL failure, exploration link, live reduced-motion fallback and no-JavaScript contact path.')
}finally{await browser.close()}
